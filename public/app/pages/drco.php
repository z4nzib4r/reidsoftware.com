                    <p>In 2018, psychology researchers at the Center for Intervention Research in Schools at Ohio University, in Athens, Ohio, partnered with JTR Studio to redesign Daily Report Card Online (DRCO), a web-based platform to help K-6 educators identify and improve upon academic and behavioral issues with their students by digitizing the widely used Daily Report Card intervention.</p>
