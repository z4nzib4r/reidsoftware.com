                    <span class="sub-heading">The Challenge</span>
                    <h2>Redesign from the ground up</h2>
                    <p>The original version of the application had been cobbled together over the course of several years, with limited flexibility, confusing user workflows, and a complete lack of mobile responsive interfaces. Our challenge was to redesign the entire platform from the ground up, enhancing features and workflows while maintaining core functionality and supporting the research objectives of the team.</p>
